#!/usr/bin/env python3
"""Create nf-raffle event configs from a Google Form and keep the event list in sync.

  add    Generate event_configs/<event>.json from a Google Form link, then run `sync`.
  sync   Regenerate the --event enum in nextflow_schema.json and the README event
         table from event_configs/*.json (optionally changing the default event).
         With --check, only report drift (used by CI).

Two kinds of form link are accepted by `add`:

* A pre-filled link (preferred). In the form editor choose "Get pre-filled link",
  type the pipeline field name as the answer to each question (email, first_name,
  run_name, ...), click "Get link" and pass the copied URL. Entry IDs are mapped
  exactly.
* A plain viewform/formResponse link. The public form page is fetched (read-only
  GET, nothing is submitted) and questions are matched to fields by their title.

In both cases the public form page is also read to find Required questions, which
become required_fields. Use --html to read a saved copy of the page instead, and
--required to set required_fields by hand when the page cannot be read.

Standard library only. Examples:

  scripts/new_event.py add --event ashg_2027 --name "ASHG 2027" \\
      --url 'https://docs.google.com/forms/d/e/<FORM_ID>/viewform?usp=pp_url&entry.1=email&...' \\
      --winner-announcement "3pm EDT on October 23rd, 2027" --set-default
  scripts/new_event.py sync --default ashg_2027
  scripts/new_event.py sync --check
"""

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path
from urllib.parse import parse_qsl, urlparse

REPO = Path(__file__).resolve().parent.parent
CONFIG_DIR = REPO / "event_configs"
SCHEMA = REPO / "nextflow_schema.json"
MAIN_NF = REPO / "main.nf"
README = REPO / "README.md"

PARTICIPANT_FIELDS = ["email", "first_name", "last_name", "affiliation"]
# Always filled by the pipeline, so the form may mark them Required.
ALWAYS_SENT_FIELDS = ["run_name", "uuid", "platform_enabled", "hostname"]
# Only filled in some contexts (see README "What gets submitted"), so must stay optional in the form.
CONTEXT_FIELDS = ["user_name", "workspace_id", "platform_workflow_id"]
ALL_FIELDS = PARTICIPANT_FIELDS + ALWAYS_SENT_FIELDS + CONTEXT_FIELDS

# Normalised question titles (lowercase, alphanumerics only) that map to each field.
TITLE_ALIASES = {
    "email": ["email", "emailaddress", "e-mail"],
    "first_name": ["firstname", "givenname", "first"],
    "last_name": ["lastname", "surname", "familyname", "last"],
    "affiliation": ["affiliation", "organization", "organisation", "company", "institution", "companyinstitution"],
    "run_name": ["runname", "nextflowrunname"],
    "uuid": ["uuid"],
    "platform_enabled": ["platformenabled", "seqeraplatformused", "seqeraplatformenabled", "towerenabled", "platformused"],
    "hostname": ["hostname", "host"],
    "user_name": ["username", "systemusername"],
    "workspace_id": ["workspaceid"],
    "platform_workflow_id": ["platformworkflowid", "workflowid"],
}

EVENTS_BEGIN = "<!-- BEGIN EVENTS: generated by scripts/new_event.py sync, do not edit by hand -->"
EVENTS_END = "<!-- END EVENTS -->"
TEXT_QUESTION_TYPES = {0, 1}  # short answer, paragraph


def die(msg):
    sys.exit(f"error: {msg}")


def normalise(text):
    return re.sub(r"[^a-z0-9]", "", text.lower().replace("e-mail", "email"))


def field_for_title(title):
    key = normalise(title)
    for field, aliases in TITLE_ALIASES.items():
        if key in {normalise(a) for a in aliases}:
            return field
    return None


def form_id_from_url(url):
    match = re.search(r"/forms/(?:u/\d+/)?d/e/([A-Za-z0-9_-]+)/(?:viewform|formResponse)", url)
    if not match:
        die(f"not a public Google Form link (expected .../forms/d/e/<id>/viewform): {url}")
    return match.group(1)


def fetch_form_page(form_id):
    url = f"https://docs.google.com/forms/d/e/{form_id}/viewform"
    request = urllib.request.Request(url, headers={"User-Agent": "nf-raffle-new-event"})
    with urllib.request.urlopen(request, timeout=30) as resp:
        return resp.read().decode("utf-8")


def parse_form_page(html):
    """Return the questions on a viewform page as (title, entry_id, required, question_type) tuples."""
    match = re.search(r"FB_PUBLIC_LOAD_DATA_\s*=\s*(.*?);\s*</script>", html, re.S)
    if not match:
        if "accounts.google.com" in html or "ServiceLogin" in html:
            die("the form requires sign-in. Set responder access to 'Anyone with the link' and turn off email collection/sign-in.")
        die("could not find form data in the page (is this a public Google Form?)")
    questions = []
    for item in json.loads(match.group(1))[1][1] or []:
        title, qtype, answers = item[1], item[3], item[4]
        if not answers:  # section headers, images, etc.
            continue
        for answer in answers:
            questions.append((title or "", f"entry.{answer[0]}", bool(answer[2]) if len(answer) > 2 else False, qtype))
    return questions


def mapping_from_prefilled(url):
    mapping = {}
    for key, value in parse_qsl(urlparse(url).query):
        if not key.startswith("entry."):
            continue
        field = value.strip() if value.strip() in ALL_FIELDS else field_for_title(value)
        if not field:
            die(f"pre-filled answer {value!r} for {key} is not a pipeline field. Use one of: {', '.join(ALL_FIELDS)}")
        if field in mapping:
            die(f"field {field!r} is pre-filled in more than one question ({mapping[field]}, {key})")
        mapping[field] = key
    return mapping


def mapping_from_questions(questions):
    mapping, unmatched = {}, []
    for title, entry, _required, _qtype in questions:
        field = field_for_title(title)
        if field is None:
            unmatched.append(title)
        elif field in mapping:
            die(f"questions {title!r} and another both look like {field!r}; use a pre-filled link instead")
        else:
            mapping[field] = entry
    if unmatched:
        print(f"warning: questions not matched to a pipeline field (they will be left blank): {unmatched}", file=sys.stderr)
    return mapping


def required_from_questions(questions, mapping):
    by_entry = {entry: field for field, entry in mapping.items()}
    required = []
    for title, entry, is_required, qtype in questions:
        field = by_entry.get(entry)
        if field and qtype not in TEXT_QUESTION_TYPES:
            print(f"warning: question {title!r} ({field}) is not a short-answer/paragraph question", file=sys.stderr)
        if not is_required:
            continue
        if field in PARTICIPANT_FIELDS:
            required.append(field)
        elif field not in ALWAYS_SENT_FIELDS:
            die(f"question {title!r} is Required in the form but the pipeline cannot always fill it. "
                f"Make it optional in the form (Google Forms silently drops entries that leave a Required question empty).")
    return [f for f in PARTICIPANT_FIELDS if f in required and f != "email"]


def cmd_add(args):
    if not re.fullmatch(r"[a-z0-9]+(_[a-z0-9]+)*", args.event):
        die("--event must be snake_case, e.g. ashg_2027")
    out = CONFIG_DIR / f"{args.event}.json"
    if out.exists() and not args.force:
        die(f"{out.relative_to(REPO)} already exists (use --force to overwrite)")

    form_id = form_id_from_url(args.url)
    prefilled = any(k.startswith("entry.") for k, _ in parse_qsl(urlparse(args.url).query))

    questions = None
    if args.html:
        questions = parse_form_page(Path(args.html).read_text(encoding="utf-8"))
    elif not (prefilled and args.required is not None):
        try:
            questions = parse_form_page(fetch_form_page(form_id))
        except OSError as exc:
            if not prefilled:
                die(f"could not fetch the form page ({exc}); pass --html with a saved copy, or use a pre-filled link with --required")
            print(f"warning: could not fetch the form page ({exc}); required fields come from --required only", file=sys.stderr)

    mapping = mapping_from_prefilled(args.url) if prefilled else mapping_from_questions(questions)
    if "email" not in mapping:
        die("the form has no question mapped to 'email'")

    if args.required is not None:
        required = [f for f in args.required.split(",") if f]
        bad = [f for f in required if f not in PARTICIPANT_FIELDS]
        if bad:
            die(f"--required accepts only {PARTICIPANT_FIELDS}, got {bad}")
    else:
        required = required_from_questions(questions, mapping) if questions else []

    missing = [f for f in ALWAYS_SENT_FIELDS + CONTEXT_FIELDS if f not in mapping]
    if missing:
        print(f"note: no question for {missing}; these will not be sent (see README 'What gets submitted')", file=sys.stderr)

    names = ["email"] + [f.replace("_", " ") for f in required]
    asks = ", ".join(names[:-1]) + " and " + names[-1]
    help_text = (f"Enter the raffle for {args.name}. "
                 + (f"Requires your {asks} to participate." if required else "Requires only your email address to participate."))
    config = {
        "event_name": args.name,
        "help": help_text,
        **({"winner_announcement": args.winner_announcement} if args.winner_announcement else {}),
        "destination_url": f"https://docs.google.com/forms/d/e/{form_id}/formResponse",
        **({"required_fields": required} if required else {}),
        "form_fields": {f: mapping[f] for f in ALL_FIELDS if f in mapping},
    }
    out.write_text(json.dumps(config, indent=2) + "\n")
    print(f"wrote {out.relative_to(REPO)}:\n{json.dumps(config, indent=2)}")
    sync(default=args.event if args.set_default else None, check=False)


def current_default():
    match = re.search(r"^(\s*event:\s*String\s*=\s*)'([^']*)'", MAIN_NF.read_text(), re.M)
    if not match:
        die("could not find `event: String = '...'` in main.nf")
    return match.group(2)


def render_events_table(events, default):
    rows = ["| Event | `--event` | Also requires |", "| --- | --- | --- |"]
    for event in events:
        config = json.loads((CONFIG_DIR / f"{event}.json").read_text())
        extra = ", ".join(f"`--{f}`" for f in config.get("required_fields", []) if f != "email") or "-"
        name = config["event_name"] + (" (default)" if event == default else "")
        rows.append(f"| {name} | `{event}` | {extra} |")
    return "\n".join(rows)


def sync(default, check):
    events = sorted(p.stem for p in CONFIG_DIR.glob("*.json"))
    default = default or current_default()
    if default not in events:
        die(f"default event {default!r} has no event_configs/{default}.json")

    schema = json.loads(SCHEMA.read_text())
    event_param = schema["$defs"]["input_output_options"]["properties"]["event"]
    event_param["enum"] = events
    event_param["default"] = default
    new_schema = json.dumps(schema, indent=2) + "\n"

    main_nf = MAIN_NF.read_text()
    new_main_nf = re.sub(r"^(\s*event:\s*String\s*=\s*)'[^']*'", rf"\g<1>'{default}'", main_nf, count=1, flags=re.M)

    readme = README.read_text()
    if EVENTS_BEGIN not in readme or EVENTS_END not in readme:
        die(f"README.md is missing the {EVENTS_BEGIN!r} / {EVENTS_END!r} markers")
    head, rest = readme.split(EVENTS_BEGIN, 1)
    _, tail = rest.split(EVENTS_END, 1)
    new_readme = f"{head}{EVENTS_BEGIN}\n{render_events_table(events, default)}\n{EVENTS_END}{tail}"

    changed = [(path, new) for path, old, new in [
        (SCHEMA, SCHEMA.read_text(), new_schema),
        (MAIN_NF, main_nf, new_main_nf),
        (README, readme, new_readme),
    ] if old != new]

    if check:
        if changed:
            die(f"out of date with event_configs/: {[str(p.relative_to(REPO)) for p, _ in changed]}. Run scripts/new_event.py sync")
        print(f"in sync: {len(events)} events, default {default}")
        return
    for path, new in changed:
        path.write_text(new)
        print(f"updated {path.relative_to(REPO)}")
    if not changed:
        print("already in sync")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    add = sub.add_parser("add", help="create event_configs/<event>.json from a Google Form link")
    add.add_argument("--event", required=True, help="event id used with --event, e.g. ashg_2027")
    add.add_argument("--name", required=True, help="display name, e.g. 'ASHG 2027'")
    add.add_argument("--url", required=True, help="pre-filled link, or viewform/formResponse link")
    add.add_argument("--winner-announcement", help="e.g. '3pm EDT on October 23rd, 2027'")
    add.add_argument("--required", help="comma-separated required_fields; overrides the Required flags read from the form")
    add.add_argument("--html", help="read the form page from this saved file instead of fetching it")
    add.add_argument("--set-default", action="store_true", help="make this the default event")
    add.add_argument("--force", action="store_true", help="overwrite an existing config")

    syn = sub.add_parser("sync", help="regenerate the --event enum, default and README event table")
    syn.add_argument("--default", help="set the default event")
    syn.add_argument("--check", action="store_true", help="fail if anything is out of date instead of writing")

    args = parser.parse_args()
    if args.command == "add":
        cmd_add(args)
    else:
        sync(default=args.default, check=args.check)


if __name__ == "__main__":
    main()
